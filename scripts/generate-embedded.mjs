import { readdirSync, readFileSync, mkdirSync, writeFileSync, statSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve('dist');
const output = path.resolve('desktop/embedded.js');
const types = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.webp': 'image/webp',
  '.woff2': 'font/woff2', '.woff': 'font/woff', '.mp3': 'audio/mpeg',
};
const files = [];
function walk(directory) {
  for (const name of readdirSync(directory)) {
    const absolute = path.join(directory, name);
    if (statSync(absolute).isDirectory()) walk(absolute);
    else files.push(absolute);
  }
}
walk(root);
const entries = files.sort().map((absolute) => {
  const url = `/${path.relative(root, absolute).split(path.sep).join('/')}`;
  const data = readFileSync(absolute).toString('base64');
  return `  ${JSON.stringify(url)}: { type: ${JSON.stringify(types[path.extname(absolute)] || 'application/octet-stream')}, data: ${JSON.stringify(data)} }`;
});
mkdirSync(path.dirname(output), { recursive: true });
mkdirSync(path.resolve('release'), { recursive: true });
writeFileSync(output, `// Generated by scripts/generate-embedded.mjs — do not edit.\nexport const embeddedFiles = {\n${entries.join(',\n')}\n};\n`);
writeFileSync(path.resolve('desktop/server-config.js'), `// Generated at build time.\nexport const buildServerUrl = ${JSON.stringify(process.env.PALIMPSEST_SERVER_URL || 'wss://3000-ic8mb6rvmkjmybn6l5alp.e2b.app/ws')};\n`);
console.log(`Embedded ${files.length} files (${(files.reduce((sum, file) => sum + statSync(file).size, 0) / 1024 / 1024).toFixed(2)} MiB)`);
